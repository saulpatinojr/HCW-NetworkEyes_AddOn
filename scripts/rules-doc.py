#!/usr/bin/env python
"""Generate docs/rules/catalog.md from the rule registry, or check it for drift (CI).

uv run python scripts/rules-doc.py           # print the catalog to stdout
uv run python scripts/rules-doc.py --write   # write docs/rules/catalog.md
uv run python scripts/rules-doc.py --check   # exit 1 when docs/rules/catalog.md differs from the registry
"""

from __future__ import annotations

import sys
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / "docs" / "rules" / "catalog.md"
sys.path.insert(0, str(ROOT / "src"))

from network_assessment.model.enforcer import assert_text_is_hedge_free  # noqa: E402
from network_assessment.model.topology import TOPOLOGY_MODEL_VERSION  # noqa: E402
from network_assessment.rules import RULES_VERSION, iter_rules  # noqa: E402


def doc() -> str:
    rules = list(iter_rules())
    for r in rules:
        for label in ("title", "remediation", "description"):
            assert_text_is_hedge_free(f"{r.id}.{label}", getattr(r, label))
    live = [r for r in rules if r.applies_to == "live-only"]
    lines = [
        "# Rule catalog",
        "",
        "Generated by `scripts/rules-doc.py --write`; do not edit by hand (CI fails on drift).",
        "",
        f"Rules version `{RULES_VERSION}`, topology model `{TOPOLOGY_MODEL_VERSION}`: {len(rules)} rules, "
        f"{len(rules) - len(live)} evaluated over an export, {len(live)} registered as live-only (reported in "
        "`unknowns[]`, never dropped).",
        "",
        "Provenance: the rules are ported from `saulpatinojr/HCW-NetworkEyes_App` at `5d3b914` (Engine A "
        "`cna/ai_engine/analysis_engine.py`, Engine B `apps/cna-api/main.py`, `bcdr_signals.py`, "
        "`finops_signals.py`); `PROVENANCE.md` lists every change. Titles, facts and remediation are hedge-free "
        "(the observed-state enforcer gates them).",
        "",
        "**[VERIFY]** every `Learn` link is the most plausible page on learn.microsoft.com as of 2026-10-10 and awaits "
        "the owner's confirmation. **[VERIFY] [REVIEW REQUIRED]** every framework control reference is a compliance "
        "claim carried over from the Core and awaits legal/compliance review before public exposure.",
        "",
        "## Rules",
        "",
        "| Id | v | Severity | Category | Applies to | Title | Evidence | Learn | Frameworks |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rules:
        frameworks = "; ".join(_fw(m) for m in r.frameworks)
        lines.append(
            f"| {r.id} | {r.version} | {r.severity.value} | {r.category} | {r.applies_to} | {_cell(r.title)} "
            f"| {_cell(r.evidence)} | [{urlsplit(r.learn_url).hostname}]({r.learn_url}) [VERIFY] "
            f"| {_cell(frameworks)} [VERIFY] |"
        )
    lines += ["", "## Texts", ""]
    for r in rules:
        lines += [
            f"### {r.id} {r.title}",
            "",
            r.description,
            "",
            f"Remediation: {r.remediation}",
            "",
            f"Evidence: {r.evidence}. Applies to: {r.applies_to}"
            + ("" if r.needs_properties else " (count-based; works without a properties column)")
            + ".",
            "",
        ]
    return "\n".join(lines)


def _fw(m) -> str:
    control = m.control or (f"{m.control_id} {m.control_name}".strip() if m.control_id or m.control_name else "")
    return f"{m.framework}{': ' + control if control else ''}"


def _cell(value: str) -> str:
    return value.replace("|", "\\|").replace("\n", " ")


if __name__ == "__main__":
    content = doc() + "\n"
    if "--write" in sys.argv:
        DOC.write_text(content, encoding="utf-8")
        print(f"wrote {DOC}")
        sys.exit(0)
    if "--check" in sys.argv:
        current = DOC.read_text(encoding="utf-8") if DOC.is_file() else ""
        if current != content:
            print(
                "ERROR: docs/rules/catalog.md has drifted from the registry "
                "(run: uv run python scripts/rules-doc.py --write)",
                file=sys.stderr,
            )
            sys.exit(1)
        print(f"docs/rules/catalog.md is in sync ({content.count(chr(10))} lines)")
        sys.exit(0)
    print(content, end="")
